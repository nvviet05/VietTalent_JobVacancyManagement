<?php
function currentLang() {
    $lang = $_SESSION['lang'] ?? 'en';
    return in_array($lang, ['en', 'vi'], true) ? $lang : 'en';
}

function langUrl($lang) {
    $params = $_GET;
    $params['lang'] = $lang;
    $params['return'] = $_SERVER['REQUEST_URI'] ?? BASE_URL . '/index.php?page=home';
    return url('set_language', $params);
}

